#!/usr/bin/env node
/**
 * Generate the machine-readable API surface from the daemon's route table.
 *
 * The route table (`packages/daemon/src/api/routes.ts`) is the single source of
 * truth. This script emits, deterministically:
 *
 *   - docs/openapi.json                     OpenAPI 3.1 document
 *   - packages/sdk/src/generated/routes.ts  typed TS route helpers
 *   - sdk/python/hotcell/_routes.py         typed Python route helpers
 *   - docs/reference.md                     generated "HTTP API" section
 *
 * Run `npm run generate:api` to rewrite them, or `npm run check:api` to fail
 * when a committed artifact is stale (CI does the latter).
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const { ROUTES } = await import(join(root, "packages/daemon/dist/api/routes.js"));
const daemonPkg = JSON.parse(readFileSync(join(root, "packages/daemon/package.json"), "utf8"));

const BANNER = "AUTO-GENERATED by scripts/generate-api.mjs from packages/daemon/src/api/routes.ts — do not edit.";

/** Path params in template order, with their declared type. */
function paramsOf(path) {
  return [...path.matchAll(/\{([^}:]+)(?::([a-z]+))?\}/g)].map((m) => ({
    name: m[1],
    type: m[2] === "int" ? "integer" : "string",
  }));
}

function paramSchema(type) {
  return type === "integer" ? { type: "integer" } : { type: "string" };
}

// --- OpenAPI -----------------------------------------------------------------

function openapi() {
  const paths = {};
  for (const route of ROUTES) {
    const operation = {
      operationId: route.id,
      summary: route.summary,
      tags: [route.tag],
      security: route.auth ? [{ bearerAuth: [] }] : [],
      parameters: paramsOf(route.path).map((p) => ({
        name: p.name,
        in: "path",
        required: true,
        schema: paramSchema(p.type),
      })),
      responses: {},
    };

    if (route.request) {
      operation.requestBody = {
        required: true,
        content: { "application/json": { schema: route.request } },
      };
    }

    if (route.stream === "websocket") {
      operation.responses["101"] = { description: "Switching protocols (WebSocket)" };
    } else {
      const contentType =
        route.stream === "sse"
          ? "text/event-stream"
          : route.stream === "html"
            ? "text/html"
            : "application/json";
      operation.responses["200"] = {
        description: "Success",
        content: { [contentType]: { schema: route.response ?? { type: "object", additionalProperties: true } } },
      };
    }

    if (route.auth) {
      operation.responses["401"] = {
        description: "Missing or invalid API key",
        content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } },
      };
    }
    operation.responses["500"] = {
      description: "Daemon error",
      content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } },
    };

    paths[route.path] ??= {};
    paths[route.path][route.method.toLowerCase()] = operation;
  }

  return {
    openapi: "3.1.0",
    info: {
      title: "hotcell API",
      version: daemonPkg.version,
      description:
        "Self-hostable sandbox infrastructure for coding agents. Generated from the daemon route table; do not edit by hand.",
    },
    servers: [{ url: "http://127.0.0.1:4750", description: "Local daemon" }],
    components: {
      securitySchemes: {
        bearerAuth: { type: "http", scheme: "bearer" },
      },
      schemas: {
        Error: {
          type: "object",
          properties: { error: { type: "string" } },
          required: ["error"],
        },
      },
    },
    paths,
  };
}

// --- TypeScript --------------------------------------------------------------

function tsRoutes() {
  const entries = ROUTES.map((route) => {
    const fields = [
      `id: ${JSON.stringify(route.id)}`,
      `method: ${JSON.stringify(route.method)}`,
      `path: ${JSON.stringify(route.path)}`,
      `summary: ${JSON.stringify(route.summary)}`,
      `tag: ${JSON.stringify(route.tag)}`,
      `auth: ${route.auth}`,
    ];
    if (route.stream) fields.push(`stream: ${JSON.stringify(route.stream)}`);
    return `  ${JSON.stringify(route.id)}: { ${fields.join(", ")} },`;
  }).join("\n");

  return `// ${BANNER}

export type HttpMethod = "GET" | "POST" | "DELETE";
export type StreamKind = "sse" | "websocket" | "html";

export interface RouteSpec {
  readonly id: string;
  readonly method: HttpMethod;
  readonly path: string;
  readonly summary: string;
  readonly tag: string;
  readonly auth: boolean;
  readonly stream?: StreamKind;
}

/** Every daemon route, keyed by its stable operation id. */
export const ROUTES = {
${entries}
} as const satisfies Record<string, RouteSpec>;

export type RouteId = keyof typeof ROUTES;

/**
 * Build a concrete path for a route id, URL-encoding each path param.
 * Throws when a required param is missing.
 */
export function buildPath(
  id: RouteId,
  params: Record<string, string | number> = {},
): string {
  const route = ROUTES[id];
  return route.path.replace(/\\{([^}:]+)(?::[a-z]+)?\\}/g, (_whole, name: string) => {
    const value = params[name];
    if (value === undefined) {
      throw new Error(\`missing path param "\${name}" for route "\${id}"\`);
    }
    return encodeURIComponent(String(value));
  });
}
`;
}

// --- Python ------------------------------------------------------------------

function pyRoutes() {
  const entries = ROUTES.map((route) => {
    const fields = [
      `"id": ${JSON.stringify(route.id)}`,
      `"method": ${JSON.stringify(route.method)}`,
      `"path": ${JSON.stringify(route.path)}`,
      `"summary": ${JSON.stringify(route.summary)}`,
      `"tag": ${JSON.stringify(route.tag)}`,
      `"auth": ${route.auth ? "True" : "False"}`,
    ];
    if (route.stream) fields.push(`"stream": ${JSON.stringify(route.stream)}`);
    return `    ${JSON.stringify(route.id)}: {${fields.join(", ")}},`;
  }).join("\n");

  return `"""${BANNER}"""

import re
from typing import Any, Dict
from urllib.parse import quote

ROUTES: Dict[str, Dict[str, Any]] = {
${entries}
}


def build_path(route_id: str, **params: Any) -> str:
    """Build a concrete path for a route id, URL-encoding each path param."""
    try:
        route = ROUTES[route_id]
    except KeyError:
        raise KeyError(f"unknown route id {route_id!r}") from None
    path = route["path"]
    for name in _PARAM_NAMES.get(route_id, ()):
        if name not in params:
            raise KeyError(f"missing path param {name!r} for route {route_id!r}")
        path = re.sub(
            r"\{" + re.escape(name) + r"(?::[a-z]+)?\}",
            quote(str(params[name]), safe=""),
            path,
        )
    return path


_PARAM_NAMES: Dict[str, tuple] = {
${ROUTES.map((route) => `    ${JSON.stringify(route.id)}: (${paramsOf(route.path).map((p) => JSON.stringify(p.name)).join(", ")}${paramsOf(route.path).length === 1 ? "," : ""}),`).join("\n")}
}
`;
}

// --- docs/reference.md -------------------------------------------------------

const BEGIN = "<!-- BEGIN GENERATED API -->";
const END = "<!-- END GENERATED API -->";

function docsSection() {
  const tags = [...new Set(ROUTES.map((r) => r.tag))];
  const lines = [
    BEGIN,
    "## HTTP API",
    "",
    "Generated from the daemon route table (`packages/daemon/src/api/routes.ts`).",
    "The full machine-readable description is [`docs/openapi.json`](./openapi.json).",
    "",
  ];
  for (const tag of tags) {
    lines.push(`### ${tag}`, "", "| Method | Path | Summary |", "| --- | --- | --- |");
    for (const route of ROUTES.filter((r) => r.tag === tag)) {
      lines.push(`| ${route.method} | \`${route.path}\` | ${route.summary} |`);
    }
    lines.push("");
  }
  lines.push(END);
  return lines.join("\n");
}

function referenceDoc() {
  const path = join(root, "docs/reference.md");
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  const section = docsSection();
  if (current.includes(BEGIN) && current.includes(END)) {
    return current.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), section);
  }
  return `${current.replace(/\s*$/, "")}\n\n${section}\n`;
}

// --- write / check -----------------------------------------------------------

const outputs = new Map([
  ["docs/openapi.json", `${JSON.stringify(openapi(), null, 2)}\n`],
  ["packages/sdk/src/generated/routes.ts", tsRoutes()],
  ["sdk/python/hotcell/_routes.py", pyRoutes()],
  ["docs/reference.md", referenceDoc()],
]);

let stale = 0;
for (const [rel, content] of outputs) {
  const abs = join(root, rel);
  const existing = existsSync(abs) ? readFileSync(abs, "utf8") : null;
  if (existing === content) continue;
  if (check) {
    stale += 1;
    console.error(`stale: ${rel}`);
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote ${relative(root, abs)}`);
  }
}

if (check) {
  if (stale > 0) {
    console.error(
      `\n${stale} generated API artifact(s) are stale. Run \`npm run generate:api\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log("generated API artifacts are up to date");
}
